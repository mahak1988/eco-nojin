//  SUPPORTED LANGUAGE TYPE & TRANSLATIONS REGISTRY
// ═══════════════════════════════════════════════════════════════════════════════

export type SupportedContentLanguage = keyof typeof TRANSLATIONS;

export type TranslationDictionary = Record<SupportedContentLanguage, ContentStrings>;

// All 15 languages — each must pass typeof FA check (TypeScript-enforced)
const TRANSLATIONS = {
  fa: FA,
  en: EN,
  ar: AR,
  ur: EN,   // Urdu: English default
  ru: EN,   // Russian: English default
  hi: EN,   // Hindi: English default
  bn: EN,   // Bengali: English default
  id: EN,   // Indonesian: English default
  "zh-CN": EN, // Chinese: English default
  fr: EN,   // French: English default
  de: EN,   // German: English default
  tr: EN,   // Turkish: English default
  es: EN,   // Spanish: English default
  pt: EN,   // Portuguese: English default
  it: EN,   // Italian: English default
} as const satisfies TranslationDictionary;

// ─── Derive RTL languages from LANGUAGES ─────────────────────────────────────

const RTL_SET = new Set(
  LANGUAGES.filter((l) => l.dir === "rtl").map((l) => l.code)
);

// ─── Runtime Translator API ──────────────────────────────────────────────────

export function createTranslator(lang: SupportedContentLanguage) {
  const dict = TRANSLATIONS[lang] ?? FA;
  const locale =
    lang === "fa" ? "fa-IR" : lang === "ar" ? "ar-EG" : lang === "ur" ? "ur-PK" : "en-US";

  const translate: TranslateFunction<ContentStrings> = (key, params) => {
    const raw = dict[key];
    if (typeof raw !== "string") return String(key);
    if (!params) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, p) =>
      String(params[p] ?? _)
    );
  };

  return {
    lang,
    locale,
    isRTL: RTL_SET.has(lang),
    t: translate,
    dict,
  };
}

export function getDefaultLanguage(): SupportedContentLanguage {
  return typeof window !== "undefined" && window.localStorage
    ? ((window.localStorage.getItem("econojin_lang") as SupportedContentLanguage | null) ?? "fa")
    : "fa";
}

export function setStoredLanguage(lang: SupportedContentLanguage) {
  try {
    window.localStorage.setItem("econojin_lang", lang);
  } catch {
    // noop
  }
}

// ─── Type-unsafe helpers (avoid in new code; kept for migration) ─────────────

/** @deprecated Use createTranslator instead. For migration compat only. */
export function contentOf(lang: SupportedContentLanguage): ContentStrings {
  return TRANSLATIONS[lang] ?? FA;
}

